export type FinanceIconName = keyof typeof financeIcons;

interface FinanceIconProps {
  name: FinanceIconName;
  className?: string;
  strokeWidth?: number;
}

export default function FinanceIcon({
  name,
  className = "h-4 w-4",
  strokeWidth = 2,
}: FinanceIconProps) {
  const Icon = financeIcons[name];
  return <Icon aria-hidden="true" className={className} strokeWidth={strokeWidth} />;
}
